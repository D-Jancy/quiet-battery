"""v10 T2 silhouettes and rimmed continuous gauge. No review-script execution."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageChops, ImageFilter
from device_shapes import KINDS, Vector, base_shape
ROOT=Path(__file__).resolve().parents[1]
PALETTES={'light':('#30332F','#B56743','#F5F2EC'),'dark':('#FFF8EA','#F1B477','#262725')}

def shape(kind):
    if kind in ('mouse','keyboard','headset','gamepad'):return base_shape(kind)
    v=Vector(16)
    if kind=='numpad':
        v.rect(4,0,8,16,'white',1)
        for y in (3,6,9,12):
            for x in (6,9):v.rect(x,y,1.3,1.3,'black',.1)
    elif kind=='earbuds':
        for x in (1,10):v.circle(x+2,3,2.6,'white');v.rect(x+1,4,2,10,'white',.8)
    elif kind=='touchpad':
        v.rect(0,2,16,12,'white',1.5);v.rect(1,10,14,1,'black');v.rect(7.5,11,1,2,'black')
    elif kind=='trackball':
        v.rect(3,3,10,12,'white',3);v.circle(8,4.5,4,'black');v.circle(8,4.5,2.7,'white');v.rect(6,11,4,1,'black')
    elif kind=='tablet':
        v.rect(0,5,16,10,'white',1);v.rect(3,7,10,6,'black',.5);v.line([(7,9),(14,0)],'white',2)
    elif kind=='pen':
        v.line([(3,13),(11,1)],'white',3);v.line([(1,16),(3,12)],'white',1);v.line([(8,3),(11,5)],'black',1)
    elif kind=='microphone':
        v.rect(5,0,6,10,'white',3);v.line([(2,5),(2,10),(5,13),(11,13),(14,10),(14,5)],'white',1.5);v.rect(7,13,2,2,'white');v.rect(3,15,10,1,'white')
    elif kind=='speaker':
        v.rect(3,0,10,16,'white',1);v.circle(8,4,2,'black');v.circle(8,11,3.2,'black');v.circle(8,11,1.5,'white')
    elif kind in ('remote','presenter'):
        v.rect(4,0,8,16,'white',2);v.circle(8,3,1.4,'black');v.rect(6,7,4,1,'black');v.rect(6,11,4,1,'black')
        if kind=='presenter':v.rect(6,1,4,1,'black')
    elif kind=='camera':
        v.rect(0,4,16,11,'white',1.5);v.rect(3,1,6,4,'white',.7);v.circle(9,9,3.2,'black');v.circle(9,9,1.6,'white')
    else:
        v.rect(2,2,12,13,'white',2);v.rect(4,4,7,1,'black');v.circle(11,12,1,'black')
    return v

def layers(kind,n,standalone=False):
    source=shape(kind).png(128).convert('RGB').getchannel('R')
    bounds=source.point(lambda p:255 if p>=96 else 0).getbbox();source=source.crop(bounds)
    gauge=4 if n<=20 else 5;gap=1 if n<=20 else 2
    area_w=n-4 if standalone else n-gauge-gap
    ratio=min(area_w/source.width,(n-4 if standalone else n-2)/source.height)
    w,h=max(1,round(source.width*ratio)),max(1,round(source.height*ratio))
    mask=source.resize((w,h),Image.Resampling.LANCZOS)
    if kind=='gamepad':
        for bx,by in ((11.5,6.2),(13.1,7.8),(11.5,9.4),(9.9,7.8)):
            xx=round((bx*8-bounds[0])*w/source.width);yy=round((by*8-bounds[1])*h/source.height)
            if 0<=xx<w and 0<=yy<h:ImageDraw.Draw(mask).point((xx,yy),fill=0)
    binary=mask.point(lambda p:255 if p>=128 else 0);padded=Image.new('L',(w+2,h+2));padded.paste(binary,(1,1));flooded=padded.copy();ImageDraw.floodfill(flooded,(0,0),255)
    outer=ImageChops.lighter(padded,ImageChops.invert(flooded));inner=outer.filter(ImageFilter.MinFilter(3)).crop((1,1,w+1,h+1))
    alpha=Image.new('L',(n,n));inside=alpha.copy();pos=((2 if standalone else 0)+(area_w-w)//2,(n-h)//2);alpha.paste(mask,pos);inside.paste(inner,pos)
    return alpha,inside

def symbol(kind,pixels=28,theme='light'):
    rim,color,_=PALETTES[theme];alpha,inner=layers(kind,pixels,standalone=True)
    icon=Image.composite(Image.new('RGBA',(pixels,pixels),color),Image.new('RGBA',(pixels,pixels),rim),inner)
    icon.putalpha(alpha)
    return icon


def generate_symbols():
    sizes=(28,35,42,56)
    output='// Generated by tools/tray_art.py from the same v10 silhouettes, without meter.\nconst SYMBOL_SIZES:[usize;4]=[28,35,42,56];\nconst SYMBOL_LAYERS:[&[u8];4]=[\n'
    for n in sizes:
        data=bytearray()
        for kind in KINDS:
            alpha,inner=layers(kind,n,standalone=True)
            for a,b in zip(alpha.tobytes(),inner.tobytes()):data.extend((a,b))
        (ROOT/f'assets/device-masks/symbol-v10-{n}.bin').write_bytes(data)
        output+=f'include_bytes!("../device-masks/symbol-v10-{n}.bin"),\n'
    (ROOT/'assets/generated/symbol_masks.rs').write_text(output+'];\n',encoding='utf-8')


def tray(kind,percent,theme='dark',pixels=16):
    n=pixels;rim,color,bg=PALETTES[theme];alpha,inner=layers(kind,n)
    icon=Image.composite(Image.new('RGBA',(n,n),color),Image.new('RGBA',(n,n),rim),inner);icon.putalpha(alpha)
    canvas=Image.new('RGBA',(n,n));canvas.alpha_composite(icon);icon=canvas
    d=ImageDraw.Draw(icon);gauge=4 if n<=20 else 5;x=n-gauge;top=1;bottom=n-2
    d.rectangle((x,top,n-1,bottom),fill=rim);d.rectangle((x+1,top+1,n-2,bottom-1),fill=bg)
    fill_h=round((bottom-top-1)*percent/100)
    if fill_h:d.rectangle((x+1,bottom-fill_h,n-2,bottom-1),fill=color)
    return icon

def generate():
    generate_symbols()
    sizes=(16,20,24,32,48)
    output='// Generated by tools/tray_art.py from approved v10 geometry.\nconst TRAY_SIZES:[usize;5]=[16,20,24,32,48];\nconst TRAY_LAYERS:[&[u8];5]=[\n'
    for n in sizes:
        data=bytearray()
        for kind in KINDS:
            alpha,inner=layers(kind,n)
            for a,b in zip(alpha.tobytes(),inner.tobytes()):data.extend((a,b))
        path=ROOT/f'assets/device-masks/tray-v10-{n}.bin';path.write_bytes(data)
        output+=f'include_bytes!("../device-masks/tray-v10-{n}.bin"),\n'
    (ROOT/'assets/generated/tray_masks.rs').write_text(output+'];\n',encoding='utf-8')
    reference_bytes=bytearray()
    for kind in ('mouse','keyboard','headset','gamepad'):
        for n in (16,20,24):
            for theme in PALETTES:
                reference=Image.open(ROOT/f'assets/source/tray-reference/tray-{kind}-{n}-{theme}.png').convert('RGBA')
                assert tray(kind,80,theme,n).tobytes()==reference.tobytes(),(kind,n,theme)
                for r,g,b,a in reference.getdata():
                    reference_bytes.extend(((a<<24)|((r*a//255)<<16)|((g*a//255)<<8)|(b*a//255)).to_bytes(4,'little'))
    (ROOT/'assets/generated/tray-v10-reference.bin').write_bytes(reference_bytes)
    print('v10 tray matches all24 approved reference rasters; generated16 type layers.')
